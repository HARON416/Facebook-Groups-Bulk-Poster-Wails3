import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

export function rgb(hex) {
  const value = hex.slice(1);
  const full = value.length === 3 ? [...value].map(c => c + c).join('') : value;
  return [0, 2, 4].map(i => parseInt(full.slice(i, i + 2), 16));
}
export function mix(a, b, amount) {
  const left = rgb(a), right = rgb(b);
  return '#' + left.map((v, i) => Math.round(v + (right[i] - v) * amount).toString(16).padStart(2, '0')).join('');
}
export function luminance(hex) {
  const [r, g, b] = rgb(hex).map(v => { v /= 255; return v <= .04045 ? v / 12.92 : ((v + .055) / 1.055) ** 2.4; });
  return r * .2126 + g * .7152 + b * .0722;
}
export function contrast(a, b) {
  const x = luminance(a), y = luminance(b);
  return (Math.max(x, y) + .05) / (Math.min(x, y) + .05);
}
function readable(color, backgrounds, minimum = 4.5) {
  if (backgrounds.every(bg => contrast(color, bg) >= minimum)) return color;
  const target = ['#000000', '#ffffff'].sort((a, b) =>
    Math.min(...backgrounds.map(bg => contrast(b, bg))) - Math.min(...backgrounds.map(bg => contrast(a, bg))))[0];
  for (let amount = .01; amount <= 1.001; amount += .01) {
    const adjusted = mix(color, target, Math.min(amount, 1));
    if (backgrounds.every(bg => contrast(adjusted, bg) >= minimum)) return adjusted;
  }
  return target;
}

// The supplied preview colors define each palette. Derive the extra UI tokens
// locally, keeping text readable on cards, inputs, hover states, and selections.
export function paletteTokens(palette) {
  palette = Object.fromEntries(Object.entries(palette).map(([key, value]) =>
    ['main', 'sub', 'text'].includes(key) && /^#[a-f0-9]{8}$/i.test(value)
      ? [key, mix(palette.bg, value.slice(0, 7), parseInt(value.slice(7), 16) / 255)] : [key, value]));
  const dark = contrast('#ffffff', palette.bg) > contrast('#000000', palette.bg);
  const direction = dark ? '#000000' : '#ffffff';
  const surface = mix(palette.bg, direction, .035);
  const hover = mix(palette.bg, direction, .065);
  // Midtone palettes can otherwise put their base and cards on opposite sides
  // of the readable text range. Keep every surface on the same side.
  const tint = (color, amount) => {
    const value = mix(palette.bg, color, amount);
    return (dark ? luminance(value) <= Math.min(luminance(palette.bg), .17)
      : luminance(value) >= Math.max(luminance(palette.bg), .19)) ? value : hover;
  };
  const active = tint(palette.main, .09);
  const backgrounds = [palette.bg, surface, hover, active];
  const accent = readable(palette.main, backgrounds);
  const text = readable(palette.text, backgrounds);
  const muted = readable(palette.sub, backgrounds);
  const dangerBg = tint(dark ? '#f29686' : '#b54735', .08);
  const warningBg = tint(dark ? '#edc078' : '#a56610', .08);
  const successBg = tint(dark ? '#8cdbac' : '#21824c', .08);
  const danger = readable(dark ? '#f29686' : '#b54735', [...backgrounds, dangerBg]);
  const warning = readable(dark ? '#edc078' : '#a56610', [...backgrounds, warningBg]);
  const success = readable(dark ? '#8cdbac' : '#21824c', [...backgrounds, successBg]);
  return { mode: dark ? 'dark' : 'light', tokens: {
    bg: palette.bg, surface, 'surface-subtle': mix(palette.bg, direction, .015),
    'surface-hover': hover, 'surface-active': active,
    border: mix(palette.bg, text, .2), 'border-strong': mix(palette.bg, text, .45),
    'border-accent': mix(palette.bg, accent, .45),
    text, 'text-strong': text, 'text-secondary': readable(mix(text, palette.bg, .15), backgrounds),
    'text-muted': muted, 'text-faint': muted, accent,
    'accent-hover': readable(mix(accent, direction, .1), backgrounds), focus: accent,
    'accent-soft': mix(palette.bg, accent, .2), 'accent-faint': mix(palette.bg, accent, .1),
    'on-accent': contrast('#ffffff', accent) >= contrast('#000000', accent) ? '#ffffff' : '#000000',
    danger, 'danger-bg': dangerBg, 'danger-border': mix(palette.bg, danger, .35),
    warning, 'warning-bg': warningBg, 'warning-border': mix(palette.bg, warning, .4),
    success, 'success-bg': successBg, scrollbar: mix(palette.bg, text, .3),
    'toast-bg': surface, 'toast-text': text, 'toast-muted': muted,
    'toast-border': mix(palette.bg, warning, .4), 'toast-success-border': mix(palette.bg, success, .4),
    'toast-success': success, 'toast-hover': hover,
  }};
}

export async function generateThemes() {
  const root = new URL('../', import.meta.url);
  const palettes = JSON.parse(await readFile(new URL('src/lib/theme-palettes.json', root), 'utf8'));
  const ids = new Set();
  const modes = {};
  let css = '/* Generated by scripts/generate-themes.mjs from theme-palettes.json. */\n';
  for (const palette of palettes) {
    if (!/^palette:[a-z0-9-]+$/.test(palette.id) || ids.has(palette.id)) throw new Error(`Invalid or duplicate theme: ${palette.id}`);
    ids.add(palette.id);
    for (const key of ['bg', 'main', 'sub', 'text']) {
      if (!/^#(?:[a-f0-9]{3}|[a-f0-9]{6}|[a-f0-9]{8})$/i.test(palette[key])) throw new Error(`Invalid ${key} in ${palette.id}`);
    }
    const { mode, tokens } = paletteTokens(palette);
    modes[palette.id] = mode;
    css += `:root[data-palette='${palette.id}'] {\n${Object.entries(tokens).map(([name, value]) => `  --${name}: ${value};`).join('\n')}\n}\n`;
  }
  await writeFile(new URL('src/palettes.css', root), css);
  await writeFile(new URL('src/lib/theme-modes.json', root), JSON.stringify(modes, null, 2) + '\n');
  await mkdir(new URL('public/', root), { recursive: true });
  await writeFile(new URL('public/theme-bootstrap.js', root), `// Generated by scripts/generate-themes.mjs. Apply before first paint.\n(() => {\n  const modes = ${JSON.stringify(modes)};\n  let saved;\n  try { saved = localStorage.getItem('postika:theme'); } catch {}\n  const palette = Object.hasOwn(modes, saved) ? saved : '';\n  const mode = palette ? modes[palette] : saved === 'light' || saved === 'dark' ? saved : matchMedia('(prefers-color-scheme: dark)').matches ? 'dark' : 'light';\n  document.documentElement.dataset.theme = mode;\n  if (palette) document.documentElement.dataset.palette = palette;\n  document.documentElement.style.colorScheme = mode;\n})();\n`);
  console.log(`Generated ${palettes.length} color palettes.`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) await generateThemes();
